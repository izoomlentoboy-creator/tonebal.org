function initAuth() {
    const savedUser = loadFromStorage('user');
    const savedAccess = loadFromStorage('access');

    if (savedUser) {
        State.user = savedUser;
        State.isAuthenticated = true;

        if (savedAccess && new Date(savedAccess.expires) > new Date()) {
            State.hasFullAccess = true;
            State.accessCode = savedAccess.code;
            State.accessExpires = savedAccess.expires;
        } else if (savedAccess) {
            // Access expired
            State.hasFullAccess = false;
            State.accessCode = savedAccess.code;
            State.accessExpires = savedAccess.expires;
        }
    }
}

function handleRegister(email, password, name) {
    // Check if user already exists
    const users = loadFromStorage('users') || [];
    const existing = users.find(u => u.email === email);

    if (existing) {
        showToast('Пользователь с таким email уже существует', 'error');
        return false;
    }

    // Create new user
    const user = {
        id: 'user_' + Date.now(),
        email,
        name,
        password, // In real app, this should be hashed
        createdAt: new Date().toISOString()
    };

    users.push(user);
    saveToStorage('users', users);

    // Log in the user
    State.user = { id: user.id, email: user.email, name: user.name };
    State.isAuthenticated = true;
    saveToStorage('user', State.user);

    closeModal();
    navigateTo('dashboard');
    showToast('Регистрация успешна! Добро пожаловать!', 'success');
    return true;
}

function handleLogin(email, password) {
    const users = loadFromStorage('users') || [];
    const user = users.find(u => u.email === email && u.password === password);

    if (!user) {
        showToast('Неверный email или пароль', 'error');
        return false;
    }

    State.user = { id: user.id, email: user.email, name: user.name };
    State.isAuthenticated = true;
    saveToStorage('user', State.user);

    // Load access if exists
    const accessData = loadFromStorage(`access_${user.id}`);
    if (accessData && new Date(accessData.expires) > new Date()) {
        State.hasFullAccess = true;
        State.accessCode = accessData.code;
        State.accessExpires = accessData.expires;
        saveToStorage('access', accessData);
    }

    closeModal();
    navigateTo('dashboard');
    showToast('Добро пожаловать!', 'success');
    return true;
}

function logout() {
    State.user = null;
    State.isAuthenticated = false;
    State.hasFullAccess = false;
    State.accessCode = null;
    State.accessExpires = null;
    localStorage.removeItem('tb_user');
    localStorage.removeItem('tb_access');
    navigateTo('home');
    showToast('Вы вышли из аккаунта');
}

function deleteAccount() {
    if (!State.user) return;

    const users = loadFromStorage('users') || [];
    const filtered = users.filter(u => u.id !== State.user.id);
    saveToStorage('users', filtered);

    // Remove user-specific data
    localStorage.removeItem(`tb_access_${State.user.id}`);

    logout();
    showToast('Аккаунт удалён', 'success');
}

function changePassword(oldPassword, newPassword) {
    if (!State.user) return false;

    const users = loadFromStorage('users') || [];
    const userIndex = users.findIndex(u => u.id === State.user.id);

    if (userIndex === -1) return false;
    if (users[userIndex].password !== oldPassword) {
        showToast('Неверный текущий пароль', 'error');
        return false;
    }

    users[userIndex].password = newPassword;
    saveToStorage('users', users);
    showToast('Пароль успешно изменён', 'success');
    return true;
}

