function activateFullAccess() {
    if (!State.user) return;

    const code = generateAccessCode();
    const expires = new Date();
    expires.setDate(expires.getDate() + 30);

    const accessData = {
        code,
        expires: expires.toISOString(),
        activatedAt: new Date().toISOString()
    };

    State.hasFullAccess = true;
    State.accessCode = code;
    State.accessExpires = accessData.expires;

    saveToStorage('access', accessData);
    saveToStorage(`access_${State.user.id}`, accessData);

    showToast('Полный доступ активирован!', 'success');
    render();
}

function extendAccess() {
    if (!State.user || !State.accessExpires) return;

    const currentExpires = new Date(State.accessExpires);
    const now = new Date();
    const baseDate = currentExpires > now ? currentExpires : now;

    baseDate.setDate(baseDate.getDate() + 30);

    const accessData = {
        code: State.accessCode || generateAccessCode(),
        expires: baseDate.toISOString(),
        activatedAt: new Date().toISOString()
    };

    State.hasFullAccess = true;
    State.accessCode = accessData.code;
    State.accessExpires = accessData.expires;

    saveToStorage('access', accessData);
    saveToStorage(`access_${State.user.id}`, accessData);

    showToast('Доступ продлён на 30 дней!', 'success');
    render();
}

function regenerateCode() {
    if (!State.user || !State.hasFullAccess) return;

    const newCode = generateAccessCode();
    State.accessCode = newCode;

    const accessData = loadFromStorage('access') || {};
    accessData.code = newCode;
    saveToStorage('access', accessData);
    saveToStorage(`access_${State.user.id}`, accessData);

    showToast('Новый код сгенерирован!', 'success');
    render();
}

function copyAccessCode() {
    if (State.accessCode) {
        navigator.clipboard.writeText(State.accessCode).then(() => {
            showToast('Код скопирован!', 'success');
        });
    }
}

