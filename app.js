function startTimer(seconds) {
    State.timerSeconds = seconds;
    State.timerRunning = true;

    State.timerInterval = setInterval(() => {
        if (State.timerSeconds > 0) {
            State.timerSeconds--;
            updateTimerDisplay();
        } else {
            stopTimer();
            showToast('Упражнение завершено!', 'success');
        }
    }, 1000);
}

function pauseTimer() {
    State.timerRunning = false;
    clearInterval(State.timerInterval);
}

function resetTimer(seconds) {
    pauseTimer();
    State.timerSeconds = seconds;
    updateTimerDisplay();
}

function stopTimer() {
    pauseTimer();
    State.timerSeconds = 0;
    updateTimerDisplay();
}

function updateTimerDisplay() {
    const display = $('.timer-display');
    if (display) {
        display.textContent = formatTime(State.timerSeconds);
    }
    const btn = $('.timer-btn.play');
    if (btn) {
        btn.textContent = State.timerRunning ? '⏸' : '▶';
    }
}

function toggleTimer(duration) {
    if (State.timerRunning) {
        pauseTimer();
    } else {
        if (State.timerSeconds === 0) {
            State.timerSeconds = duration;
        }
        startTimer(State.timerSeconds);
    }
    updateTimerDisplay();
}

